-- Korg Z1 Filter 1 & 2 + EG3 (Filter EG) Preset Tests (Electra One firmware 5.0+)

local function assertSysex(msg, expected)
    test.eq(msg.type, SYSEX, "expected a SysEx message")
    test.count(msg.data, #expected, "SysEx byte length")
    for i = 1, #expected do
        test.eq(msg.data[i], expected[i], string.format("byte %d", i))
    end
end

test.case("Top section sends Filter Routing (258), EG Knob Tgt (260), Filter 1 Type (261), F1/F2 Cutoff (263/290)", function()
    test.turn(1, 2)
    test.turn(3, 2)
    test.turn(6, 4)
    test.turn(8, 80)
    test.turn(12, 65)

    local sent = test.sent()
    test.count(sent, 5)
    assertSysex(sent[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x02, 0x02, 0x02, 0x00, 0xF7 })
    assertSysex(sent[2], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x04, 0x02, 0x03, 0x00, 0xF7 })
    assertSysex(sent[3], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x05, 0x02, 0x05, 0x00, 0xF7 })
    assertSysex(sent[4], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x07, 0x02, 0x50, 0x00, 0xF7 })
    assertSysex(sent[5], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x22, 0x02, 0x41, 0x00, 0xF7 })
end)

test.case("Assigned Cutoff EG dx7envelope follows F1/F2 Cut ModEG and switches between EG1..EG4 & Amp EG", function()
    test.turn(20, 0)
    test.eq(controls.get(4):getName(), "F1 EG3")
    test.eq(controls.get(5):isVisible(), true)
    test.clear()

    test.turn(4, 45, "r1")
    test.turn(5, -20)
    test.count(test.sent(), 2)
    assertSysex(test.sent()[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x46, 0x00, 0x2D, 0x00, 0xF7 })
    assertSysex(test.sent()[2], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x45, 0x00, 0x6C, 0x7F, 0xF7 })
    test.clear()

    test.turn(21, 0)
    test.count(test.sent(), 1)
    assertSysex(test.sent()[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x0C, 0x02, 0x01, 0x00, 0xF7 })
    test.eq(controls.get(4):getName(), "F1 EG1")
    test.clear()
    test.turn(4, 88, "r1")
    test.count(test.sent(), 1)
    assertSysex(test.sent()[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x20, 0x00, 0x58, 0x00, 0xF7 })

    test.clear()
    test.turn(20, 1)
    test.none(test.sent())
    test.eq(controls.get(4):getName(), "F2 EG3")
    test.eq(controls.get(4):getValue("r1"):getValue(), 45, "EG3 r1 value 45 preserved")

    test.turn(21, 4)
    test.eq(controls.get(4):getName(), "F2 Amp EG")
    test.eq(controls.get(5):isVisible(), false, "Amp EG has no Start Level fader")
    test.clear()
    test.turn(4, 64, "r1")
    test.count(test.sent(), 1)
    assertSysex(test.sent()[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x4E, 0x02, 0x40, 0x00, 0xF7 })
end)

test.case("2BPF Band-B bottom row is hidden for LPF/HPF/BPF/BRF and appears only when Filter Type is 2BPF", function()
    test.turn(20, 0)
    test.turn(6, 1)
    test.eq(controls.get(34):isVisible(), false, "2BPF CutB hidden when F1 is HPF")
    test.clear()
    test.turn(34, 77)
    test.none(test.sent(), "hidden 2BPF control must not transmit")

    test.turn(6, 4)
    test.eq(controls.get(34):isVisible(), true, "2BPF CutB visible when F1 is 2BPF")
    test.clear()
    test.turn(34, 82)
    test.count(test.sent(), 1)
    assertSysex(test.sent()[1], { 0xF0, 0x42, 0x30, 0x46, 0x41, 0x01, 0x16, 0x02, 0x52, 0x00, 0xF7 })

    test.turn(20, 1)
    test.eq(controls.get(34):isVisible(), false, "2BPF CutB hidden for Filter 2 (LPF)")
end)
